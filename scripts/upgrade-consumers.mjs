#!/usr/bin/env node

/**
 * Controlled Cross-Repository Upgrade Engine for @amoga/ui
 *
 * Enforces:
 * 1. Only package.json and lockfile modification
 * 2. Strict protection of app/, features/, components/custom/, API, state code
 * 3. Machine-readable consumers registry update
 * 4. PR creation template with release notes, CI checklist, and rollback steps
 */

import fs from 'fs'
import path from 'path'
import { execSync } from 'child_process'
import { fileURLToPath } from 'url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const registryPath = path.resolve(__dirname, '../consumers-registry.json')
const amogaPackagePath = path.resolve(__dirname, '../package.json')

if (!fs.existsSync(registryPath) || !fs.existsSync(amogaPackagePath)) {
  console.error('❌ Registry or package.json missing.')
  process.exit(1)
}

const registry = JSON.parse(fs.readFileSync(registryPath, 'utf-8'))
const amogaPackage = JSON.parse(fs.readFileSync(amogaPackagePath, 'utf-8'))
const targetVersion = process.env.TARGET_VERSION || amogaPackage.version
const releaseNotes = process.env.RELEASE_NOTES || `Automated upgrade to @amoga/ui@${targetVersion}`

console.log(`🚀 Starting Cross-Repository Upgrade for @amoga/ui@${targetVersion}`)

/**
 * Generate PR Description Body with safety warnings, validation checklist, and rollback commands
 */
export function generatePrBody({ appName, currentVersion, newVersion, releaseNotes }) {
  const isMajor = newVersion.split('.')[0] !== currentVersion.split('.')[0]
  const breakingAlert = isMajor
    ? `> [!WARNING]\n> **MAJOR VERSION UPGRADE**: This release may contain breaking changes or deprecated API removals. Review the migration guide carefully before merging.`
    : `> [!NOTE]\n> **Backwards-Compatible Release**: This upgrade introduces fixes and new features with zero breaking changes to existing APIs.`

  return `
## 📦 AmogaDS Central Upgrade: \`@amoga/ui@${newVersion}\`

Automated dependency upgrade for **${appName}**.

### 📋 Version Diff
- **Previous Version**: \`v${currentVersion}\`
- **Target Version**: \`v${newVersion}\`

${breakingAlert}

---

### 📝 Release Notes & Highlights
${releaseNotes}

---

### 🛡 Automated Safety Verification
This PR was generated by the controlled cross-repository upgrade engine:
- [x] **Strict File Boundary**: ONLY \`package.json\` and lockfile were modified.
- [x] **Zero Code Overwrites**: \`app/\`, \`features/\`, \`components/custom/\`, and business logic were NOT touched.
- [ ] **Consuming App CI Check**: Pending CI validation on this branch.
- [ ] **Build Verification**: Run \`npm run build\` locally or in CI.

---

### 🧪 Reviewer Checklist
Before merging this PR:
1. [ ] Verify CI checks have passed on this branch.
2. [ ] Test desktop, tablet, and mobile viewport layouts.
3. [ ] Verify light mode and dark mode theme switching.
4. [ ] Check core flows (Forms, Dialogs, Tables, and Navigation).

---

### ⏪ Rollback Instructions
If any regression is discovered after merging or deploying:
\`\`\`bash
# Revert to previous stable version
npm install @amoga/ui@${currentVersion}
npm run build
\`\`\`
`
}

/**
 * Validate that no unauthorized application files were modified
 */
export function validateFileModifications(modifiedFiles) {
  const allowedPatterns = [/^package\.json$/, /^package-lock\.json$/, /^pnpm-lock\.yaml$/, /^yarn\.lock$/]

  const unauthorizedFiles = modifiedFiles.filter((file) => {
    const trimmed = file.trim()
    if (!trimmed) return false
    return !allowedPatterns.some((pattern) => pattern.test(trimmed))
  })

  if (unauthorizedFiles.length > 0) {
    throw new Error(
      `CRITICAL SAFETY VIOLATION: Automation attempted to modify application code: \n${unauthorizedFiles.join('\n')}`
    )
  }
}

